"""Package selected Alpine aarch64 CLI binaries as signed HAP libraries."""
import argparse
import hashlib
import json
import posixpath
from pathlib import Path
import tarfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "docs/guest-tools-lock.json"
NATIVE = ROOT / "entry/libs/arm64-v8a"
CPP = ROOT / "entry/src/main/cpp/guest-tools.inc"
ARCHIVE = ROOT / "entry/src/main/resources/rawfile/shell-tools-layer.zip"

BINS = {"usr/bin/git", "usr/bin/python3.12", "usr/libexec/git-core/git-remote-http"}
ALIASES = {
    "usr/bin/python": "usr/bin/python3.12",
    "usr/bin/python3": "usr/bin/python3.12",
    "usr/libexec/git-core/git-remote-https": "usr/libexec/git-core/git-remote-http",
}
DATA_PREFIXES = ("usr/lib/python3.12/", "usr/share/git-core/templates/")
CA_CERT = "etc/ssl/certs/ca-certificates.crt"


def select_packages(directory):
    binaries, data, links = {}, {}, {}
    for entry in json.loads(LOCK.read_text())["packages"]:
        source = directory / entry["archive"]
        with source.open("rb") as stream:
            digest = hashlib.file_digest(stream, "sha256").hexdigest()
        if digest != entry["sha256"]:
            raise ValueError(f"Unexpected hash for {source.name}")
        with tarfile.open(source, ignore_zeros=True) as package:
            for member in package:
                name = member.name
                if name.startswith("usr/lib/") and member.issym():
                    target = posixpath.normpath(posixpath.join(posixpath.dirname(name), member.linkname))
                    links[name] = target
                if not member.isfile():
                    continue
                if name in BINS or name == CA_CERT or name.startswith((*DATA_PREFIXES, "usr/lib/")):
                    payload = package.extractfile(member).read()
                    if payload.startswith(b"\x7fELF"):
                        binaries[name] = payload
                    elif name == CA_CERT or name.startswith(DATA_PREFIXES):
                        data[name] = payload
    data["etc/ssl/cert.pem"] = data[CA_CERT]
    return binaries, data, links


def write_hap_inputs(binaries, data, links):
    names = {}
    for destination, payload in sorted(binaries.items()):
        name = "libguest_cli_" + hashlib.sha256(destination.encode()).hexdigest()[:12] + ".so"
        (NATIVE / name).write_bytes(payload)
        (NATIVE / name).chmod(0o755)
        names[destination] = name
    for alias, original in {**links, **ALIASES}.items():
        if original in names:
            names[alias] = names[original]
    CPP.write_text(
        "/* Generated by scripts/package-shell-tools.py. */\n"
        + "".join(f'{{ "{name}", "/{destination}" }},\n' for destination, name in sorted(names.items()))
    )
    directories = sorted({
        str(parent) + "/" for file in [*data, *names]
        for parent in Path(file).parents if parent != Path(".")
    })
    with zipfile.ZipFile(ARCHIVE, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for directory in directories:
            archive.writestr(directory, b"")
        for file, payload in sorted(data.items()):
            archive.writestr(zipfile.ZipInfo(file), payload, compress_type=zipfile.ZIP_DEFLATED)
    print(f"Packaged {len(binaries)} ELF inputs, {len(names)} bindings and {len(data)} data files")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("package_directory", type=Path)
    args = parser.parse_args()
    write_hap_inputs(*select_packages(args.package_directory))
